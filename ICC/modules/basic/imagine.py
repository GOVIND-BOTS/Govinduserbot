import base64
import os
import tempfile
from pathlib import Path

import aiohttp
from pyrogram import Client, filters
from pyrogram.types import Message

from ICC.modules.help import add_command_help


@Client.on_message(filters.command("imagine", ".") & filters.me)
async def generate_image(client: Client, message: Message):
    parts = (message.text or "").split(maxsplit=1)
    if len(parts) < 2 or not parts[1].strip():
        return await message.edit_text(
            "Usage: `.imagine <your image prompt>`\n"
            "Example: `.imagine a cinematic photo of a tiger in a snowy forest`"
        )

    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        return await message.edit_text(
            "`OPENAI_API_KEY` is not configured. Add it to your server environment variables."
        )

    prompt = parts[1].strip()
    if len(prompt) > 3000:
        return await message.edit_text("Prompt is too long. Please keep it under 3000 characters.")

    status = await message.edit_text("🎨 **ICC AI is creating your image...**\nPlease wait a moment.")
    timeout = aiohttp.ClientTimeout(total=300, connect=30)
    try:
        async with aiohttp.ClientSession(timeout=timeout) as session:
            async with session.post(
                "https://api.openai.com/v1/images/generations",
                headers={
                    "Authorization": f"Bearer {api_key}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": "gpt-image-2.6-flare",
                    "prompt": prompt,
                    "n": 1,
                    "size": "1024x1024",
                    "quality": "high",
                    "output_format": "png",
                    "moderation": "auto",
                },
            ) as response:
                payload = await response.json(content_type=None)
                if response.status != 200:
                    detail = payload.get("error", {}).get("message", f"HTTP {response.status}")
                    raise RuntimeError(detail)

        images = payload.get("data") or []
        encoded = images[0].get("b64_json") if images else None
        if not encoded:
            raise RuntimeError("The image API returned no image data.")

        image_bytes = base64.b64decode(encoded)
        with tempfile.TemporaryDirectory(prefix="icc_imagine_") as folder:
            image_path = Path(folder) / "icc_ai_image.png"
            image_path.write_bytes(image_bytes)
            await client.send_photo(
                chat_id=message.chat.id,
                photo=str(image_path),
                caption=f"✨ **Generated by ICC AI**\n\n{prompt[:850]}",
            )
        await status.delete()
    except Exception as exc:
        await status.edit_text(f"❌ **Image generation failed:**\n`{str(exc)[:700]}`")


add_command_help("imagine", [[
    ".imagine <prompt>",
    "Generate an AI image from a text prompt using the OpenAI Image API.",
]])
